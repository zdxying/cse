#!/usr/bin/env python3
"""Generate a differential-execution driver for the sf_/ref_ twin convention.

A fixture following the convention pairs every //@cse-marked `sf_X(...)` with an
unmarked `ref_X(...)` that has an identical body. Optimizing the marked region
and leaving the twin alone puts the two implementations in the same translation
unit, so a generated `main` can call both on the same inputs and compare.

    gen_twin_main.py <optimized.cse> <out.cpp>

The generated program includes <optimized.cse>, calls each comparable pair over a
seeded random stream plus a set of edge values, and compares return values. It
prints `TWIN-DIFF PASSED` / `TWIN-DIFF FAILED` / `TWIN-DIFF SKIPPED (no pairs)`.

Only pairs whose parameters and return type are scalar (double/float/int/
unsigned) are exercised; anything involving pointers, arrays, references or
structs is skipped and counted. This is a deliberate v1 boundary -- those cases
need a memory model the generator does not have yet.
"""

import re
import sys

SCALAR = {"double", "float", "int", "unsigned", "long", "short"}

# `ret name(params) {` -- a single-line signature. The fixtures keep signatures
# on one line; multi-line signatures are simply not matched and their pair is
# skipped (counted), never silently mis-parsed.
SIG_RE = re.compile(
    r"^\s*(?P<ret>[A-Za-z_][A-Za-z0-9_ ]*?)\s+"
    r"(?P<name>[A-Za-z_]\w*)\s*\((?P<params>[^)]*)\)\s*\{"
)


def parse_functions(text):
    funcs = {}
    for line in text.splitlines():
        m = SIG_RE.match(line)
        if not m:
            continue
        ret = m.group("ret").strip()
        name = m.group("name")
        params = []
        raw = m.group("params").strip()
        if raw and raw != "void":
            for p in raw.split(","):
                parts = p.strip().split()
                if len(parts) < 2:
                    params = None
                    break
                params.append((parts[0], parts[-1]))
        if params is None:
            continue
        funcs[name] = (ret, params)
    return funcs


def is_scalar(t):
    return t in SCALAR


def arg_expr(t):
    # The first 8 iterations sweep the edge values; after that, random. `t` is
    # the generated loop counter (an int), so indexing edges_d/edges_i is safe.
    if t in ("double", "float"):
        return "(t < 8 ? edges_d[t] : ud(rng))"
    return "(t < 8 ? edges_i[t] : ui(rng))"


def gen_call(name, params, indent):
    ref = "ref_" + name[3:]
    lines = [f"{indent}{{",
             f'{indent}  const char* fname = "{name}";']
    for i, (t, _) in enumerate(params):
        lines.append(f"{indent}  {t} a{i} = {arg_expr(t)};")
    arglist = ", ".join(f"a{i}" for i in range(len(params)))
    lines.append(f"{indent}  auto got = {name}({arglist});")
    lines.append(f"{indent}  auto want = {ref}({arglist});")
    lines.append(f"{indent}  if (!same(want, got)) {{")
    lines.append(f"{indent}    ++failures;")
    lines.append(f"{indent}    if (failures <= 20)")
    lines.append(f'{indent}      std::printf("MISMATCH %s: got %.17g want %.17g\\n", fname, (double)got, (double)want);')
    lines.append(f"{indent}  }}")
    lines.append(f"{indent}}}")
    return lines


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_twin_main.py <optimized.cse> <out.cpp>\n")
        return 2
    cse_path, out_path = sys.argv[1], sys.argv[2]
    text = open(cse_path, encoding="utf-8", errors="replace").read()
    funcs = parse_functions(text)

    pairs = []
    skipped = 0
    for name, (ret, params) in funcs.items():
        if not name.startswith("sf_"):
            continue
        ref = "ref_" + name[3:]
        if ref not in funcs:
            skipped += 1
            continue
        rret, rparams = funcs[ref]
        if not is_scalar(ret) or ret == "void":
            skipped += 1
            continue
        if len(params) != len(rparams) or not all(is_scalar(t) for t, _ in params):
            skipped += 1
            continue
        pairs.append((name, ret, params))

    body = []
    body.append("// Auto-generated by tests/verify/gen_twin_main.py -- do not edit.")
    body.append(f'#include "{cse_path}"')
    body.append("#include <cmath>")
    body.append("#include <cstdint>")
    body.append("#include <cstdio>")
    body.append("#include <cstring>")
    body.append("#include <random>")
    body.append("")
    body.append("static std::mt19937_64 rng(0xC5E5EED);")
    body.append("static std::uniform_real_distribution<double> ud(-1000.0, 1000.0);")
    body.append("static std::uniform_int_distribution<int> ui(-100, 100);")
    body.append("static const double edges_d[8] = {0.0, -0.0, 1.0, -1.0, 1e308, -1e308, 0.5, -0.5};")
    body.append("static const int edges_i[8] = {0, 1, -1, 2, -2, 7, -7, 100};")
    body.append("static int failures = 0;")
    body.append("")
    body.append("static bool same(double want, double got) {")
    body.append("  // Bit-for-bit: the twin differential runs under -s, where no pass may")
    body.append("  // reassociate floating point, so the optimized twin must reproduce the")
    body.append("  // untouched one exactly -- including the sign of zero. `want == got`")
    body.append("  // would accept +0.0 == -0.0, hiding a sign-of-zero miscompile. A NaN")
    body.append("  // pair with differing payload bits stays equal (the payload is not a")
    body.append("  // semantic result).")
    body.append("  uint64_t wb, gb;")
    body.append("  std::memcpy(&wb, &want, sizeof(wb));")
    body.append("  std::memcpy(&gb, &got, sizeof(gb));")
    body.append("  if (wb == gb) return true;")
    body.append("  return (want != want) && (got != got);")
    body.append("}")
    body.append("")
    body.append("int main() {")
    if not pairs:
        body.append('  std::printf("TWIN-DIFF SKIPPED (no comparable pairs)\\n");')
        body.append("  return 0;")
        body.append("}")
        open(out_path, "w").write("\n".join(body) + "\n")
        return 0
    body.append("  const int ITERS = 2000;")
    body.append("  for (int t = 0; t < ITERS; ++t) {")
    for name, ret, params in pairs:
        body.extend(gen_call(name, params, "    "))
    body.append("  }")
    body.append('  if (failures) { std::printf("TWIN-DIFF FAILED: %d mismatches\\n", failures); return 1; }')
    body.append(f'  std::printf("TWIN-DIFF PASSED (%d pairs)\\n", {len(pairs)});')
    body.append("  return 0;")
    body.append("}")
    open(out_path, "w").write("\n".join(body) + "\n")
    if skipped:
        sys.stderr.write(f"gen_twin_main: {len(pairs)} pairs, {skipped} skipped\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
